#!/usr/bin/env python3
"""Writes the country list the profile picker, the posts and Insights use.

From Unicode CLDR's territory names (the `cldr-localenames-full` npm package),
so a country is named the way people who speak each of the app's languages
name it, without anybody translating 250 names 68 times by hand:

    npm pack cldr-localenames-full@47.0.0 && tar xzf cldr-localenames-full-*.tgz
    python3 scripts/generate-countries.py package/main

Writes:
  app/assets/countries/<language>.json   code -> name, one per app language
  app/lib/models/countries.g.dart        the codes, for the picker's order
  api/src/common/countries.ts            the codes, for the server to check

Codes are ISO 3166-1 alpha-2, plus XK for Kosovo, which ISO has not assigned
but every phone and passport office uses. CLDR's other two-letter territories
are left out: the EU, the UN and the like are not where somebody lives, and
AC, CP, DG, EA, IC and TA are parts of countries already on the list.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOT_COUNTRIES = {
    "AC", "CP", "CQ", "DG", "EA", "EU", "EZ", "IC", "QO", "TA", "UN",
    "XA", "XB", "ZZ",
}
# The name somebody writes on a form: "Hong Kong", not "Hong Kong SAR China".
SHORT = {"HK", "MO", "PS", "MM"}
# The app's code where CLDR's differs.
CLDR_LOCALE = {"tl": "fil"}


def app_languages() -> list[str]:
    return sorted(
        p.stem.removeprefix("app_")
        for p in (ROOT / "app/lib/l10n").glob("app_*.arb")
    )


def names(cldr: Path, language: str) -> dict[str, str]:
    locale = CLDR_LOCALE.get(language, language)
    data = json.loads((cldr / locale / "territories.json").read_text("utf-8"))
    table = data["main"][locale]["localeDisplayNames"]["territories"]
    out = {}
    for code, name in table.items():
        if len(code) != 2 or not code.isalpha() or code in NOT_COUNTRIES:
            continue
        out[code] = table.get(f"{code}-alt-short", name) if code in SHORT else name
    return out


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    cldr = Path(sys.argv[1])
    english = names(cldr, "en")
    codes = sorted(english)

    out = ROOT / "app/assets/countries"
    out.mkdir(parents=True, exist_ok=True)
    for language in app_languages():
        local = names(cldr, language)
        # A name CLDR lacks in one language falls back to English rather than
        # leaving a country out of that language's picker.
        table = {code: local.get(code, english[code]) for code in codes}
        (out / f"{language}.json").write_text(
            json.dumps(table, ensure_ascii=False, separators=(",", ":")) + "\n",
            "utf-8",
        )

    listed = "\n".join(f"  '{c}'," for c in codes)
    (ROOT / "app/lib/models/countries.g.dart").write_text(
        "// GENERATED by scripts/generate-countries.py. Do not edit.\n\n"
        "/// Every country somebody can say they are in: ISO 3166-1 alpha-2,\n"
        "/// plus XK for Kosovo.\n"
        f"const countryCodes = <String>[\n{listed}\n];\n",
        "utf-8",
    )
    quoted = "\n".join(f"  '{c}'," for c in codes)
    (ROOT / "api/src/common/countries.ts").write_text(
        "// GENERATED by scripts/generate-countries.py. Do not edit.\n\n"
        "/** Every country somebody can say they are in: ISO 3166-1 alpha-2,\n"
        " * plus XK for Kosovo. Names are the app's, in the reader's language. */\n"
        f"export const COUNTRY_CODES: readonly string[] = [\n{quoted}\n];\n\n"
        "const known = new Set(COUNTRY_CODES);\n\n"
        "export function isCountryCode(value: unknown): value is string {\n"
        "  return typeof value === 'string' && known.has(value);\n"
        "}\n",
        "utf-8",
    )
    print(f"{len(codes)} countries, {len(app_languages())} languages")


if __name__ == "__main__":
    main()
