-- Where somebody is, as a country picked from a list rather than typed.
--
-- `location` was free text, so it could not be counted ("Lagos", "lagos
-- nigeria", "9ja", "🌍") and could say anything at all. The app now offers a
-- list of countries; this column holds the ISO 3166-1 code it picks.
