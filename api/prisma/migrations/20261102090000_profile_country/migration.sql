typed AS (
  SELECT id,
         lower(btrim(location)) AS whole,
         lower(btrim(regexp_replace(location, '^.*,', ''))) AS last
  FROM "UserProfile"
  WHERE location IS NOT NULL AND btrim(location) <> ''
)
UPDATE "UserProfile" p
SET country = COALESCE(w.code, l.code)
FROM typed t
LEFT JOIN names w ON w.name = t.whole
LEFT JOIN names l ON l.name = t.last
WHERE p.id = t.id AND COALESCE(w.code, l.code) IS NOT NULL;
